#!/bin/sh
set -eu

usage() {
    cat <<'EOF'
Usage:
  install.sh --node-key KEY --server-address ADDRESS [--mqvpn-url URL]
  install.sh --node-key KEY --server-address ADDRESS --mqvpn-binary PATH

Environment equivalents:
  WEARLESS_NODE_KEY
  WEARLESS_SERVER_ADDRESS
  MQVPN_URL
  MQVPN_BINARY

The node key is written only to /etc/wearless/node.conf with mode 0600.
The mqvpn binary URL is intentionally not embedded: the exact official
release URL was not present in the provided sources.
EOF
}

fail() {
    printf '%s\n' "$*" >&2
    exit 1
}

node_key=${WEARLESS_NODE_KEY:-}
server_address=${WEARLESS_SERVER_ADDRESS:-}
mqvpn_url=${MQVPN_URL:-"TO VERIFY — official release URL"}
mqvpn_binary=${MQVPN_BINARY:-}

while [ "$#" -gt 0 ]; do
    case "$1" in
        --node-key)
            [ "$#" -ge 2 ] || fail "--node-key requires a value"
            node_key=$2
            shift 2
            ;;
        --server-address)
            [ "$#" -ge 2 ] || fail "--server-address requires a value"
            server_address=$2
            shift 2
            ;;
        --mqvpn-url)
            [ "$#" -ge 2 ] || fail "--mqvpn-url requires a value"
            mqvpn_url=$2
            shift 2
            ;;
        --mqvpn-binary)
            [ "$#" -ge 2 ] || fail "--mqvpn-binary requires a value"
            mqvpn_binary=$2
            shift 2
            ;;
        -h|--help)
            usage
            exit 0
            ;;
        *)
            fail "Unknown argument: $1"
            ;;
    esac
done

[ "$(id -u)" -eq 0 ] || fail "Run as root"
[ -n "$node_key" ] || fail "Missing node key (WEARLESS_NODE_KEY or --node-key)"
[ -n "$server_address" ] || fail "Missing server address (WEARLESS_SERVER_ADDRESS or --server-address)"

printf '%s' "$node_key" | LC_ALL=C grep -q '[[:cntrl:][:space:]]' &&
    fail "Node key must not contain whitespace or control characters"
printf '%s' "$server_address" | LC_ALL=C grep -q '[[:cntrl:][:space:]]' &&
    fail "Server address must not contain whitespace or control characters"

[ -r /etc/os-release ] || fail "/etc/os-release is missing"
. /etc/os-release
case "${ID:-}:${VERSION_ID:-}" in
    ubuntu:22.04|debian:12) ;;
    *) fail "Unsupported OS: ${PRETTY_NAME:-unknown}. Ubuntu 22.04 and Debian 12 are supported." ;;
esac

for command_name in systemctl install mktemp grep getent useradd nc; do
    command -v "$command_name" >/dev/null 2>&1 ||
        fail "Required command is missing: $command_name"
done

script_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
[ -f "$script_dir/wearless-node.service" ] || fail "wearless-node.service is missing"
[ -f "$script_dir/control.sh" ] || fail "control.sh is missing"
[ -f "$script_dir/stats.sh" ] || fail "stats.sh is missing"

if ! getent passwd wearless-node >/dev/null 2>&1; then
    useradd --system --no-create-home --shell /usr/sbin/nologin wearless-node
fi

install -d -m 0700 -o root -g root /etc/wearless
install -d -m 0700 -o root -g root /var/log/wearless

umask 077
config_tmp=$(mktemp /etc/wearless/node.conf.XXXXXX)
trap 'rm -f "$config_tmp"' EXIT HUP INT TERM
cat >"$config_tmp" <<EOF
# Wearless node configuration. Generated by install.sh.
# Public server address for clients: $server_address
[Interface]
Listen = 0.0.0.0:443
Subnet = 10.0.0.0/24
TunName = mqvpn0

[Auth]
User = wearless-owner:$node_key

[Control]
Listen = 127.0.0.1:9090
EOF
chmod 0600 "$config_tmp"
mv "$config_tmp" /etc/wearless/node.conf
trap - EXIT HUP INT TERM

binary_tmp=""
install_binary() {
    [ -s "$1" ] || fail "mqvpn binary is empty or missing"
    chmod 0755 "$1"
    install -m 0755 "$1" /usr/local/bin/mqvpn
}

if [ -n "$mqvpn_binary" ]; then
    [ -f "$mqvpn_binary" ] || fail "MQVPN_BINARY does not exist: $mqvpn_binary"
    install_binary "$mqvpn_binary"
elif [ "$mqvpn_url" != "TO VERIFY — official release URL" ]; then
    command -v curl >/dev/null 2>&1 || fail "curl is required to download MQVPN_URL"
    binary_tmp=$(mktemp /usr/local/bin/.mqvpn.XXXXXX)
    trap 'rm -f "$binary_tmp"' EXIT HUP INT TERM
    curl --fail --location --retry 3 --output "$binary_tmp" "$mqvpn_url"
    install_binary "$binary_tmp"
    rm -f "$binary_tmp"
    trap - EXIT HUP INT TERM
elif [ -x /usr/local/bin/mqvpn ]; then
    :
else
    fail "MQVPN_URL is 'TO VERIFY — official release URL'. Verify and set it to the exact official direct binary URL, or set MQVPN_BINARY."
fi

install -m 0750 "$script_dir/control.sh" /usr/local/sbin/wearless-control
install -m 0750 "$script_dir/stats.sh" /usr/local/sbin/wearless-stats
install -m 0644 "$script_dir/wearless-node.service" /etc/systemd/system/wearless-node.service

if command -v ufw >/dev/null 2>&1 && ufw status 2>/dev/null | grep -q '^Status: active'; then
    ufw allow 443/udp
elif command -v firewall-cmd >/dev/null 2>&1 && firewall-cmd --state >/dev/null 2>&1; then
    firewall-cmd --permanent --add-port=443/udp
    firewall-cmd --reload
elif command -v iptables >/dev/null 2>&1; then
    iptables -C INPUT -p udp --dport 443 -j ACCEPT 2>/dev/null ||
        iptables -I INPUT -p udp --dport 443 -j ACCEPT
    if command -v ip6tables >/dev/null 2>&1; then
        ip6tables -C INPUT -p udp --dport 443 -j ACCEPT 2>/dev/null ||
            ip6tables -I INPUT -p udp --dport 443 -j ACCEPT
    fi
else
    printf '%s\n' "No host firewall manager detected; ensure UDP 443 is open upstream." >&2
fi

systemctl daemon-reload
systemctl enable --now wearless-node.service
systemctl restart wearless-node.service

printf '%s\n' "Wearless node installed. Configuration: /etc/wearless/node.conf (0600)"
